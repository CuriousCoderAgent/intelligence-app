// Writes docs/IMAGE_PROMPTS.md: one ready-to-paste image prompt per card that
// does not have a picture yet. Paste a prompt into ChatGPT (or any image
// model), save the result as <id>.png in image-inbox/, then run `npm run images`.
// The framing rules are explained in docs/CHATGPT_BRIEF.md.
import { existsSync, mkdirSync, readdirSync, writeFileSync } from 'node:fs'
import { loadDeckOrExit } from './lib/deck.mjs'

const { topics: CATEGORIES, facts: FACTS } = loadDeckOrExit()
const CATEGORY_BY_ID = Object.fromEntries(CATEGORIES.map((topic) => [topic.id, topic]))

const CARDS_DIR = new URL('../src/assets/cards/', import.meta.url)
const OUT = new URL('../docs/IMAGE_PROMPTS.md', import.meta.url)

/** One shared style so the whole deck looks like a single series. */
export const STYLE =
  'Style: rich editorial illustration, painterly digital art with bold simplified shapes, dramatic cinematic lighting and a subtle film grain. No text, letters, numbers, logos, borders or watermarks anywhere in the image.'

export const FRAMING =
  'Format: vertical 2:3 portrait, 1024 x 1536 pixels. Centre the main subject and place it about one third of the way down. Leave a little plain background above it. Keep the bottom 40% of the image dark, simple and free of detail, because it fades into a text panel.'

export const promptFor = (fact) =>
  [
    `Illustration of ${fact.visual}.`,
    `Colour palette: ${CATEGORY_BY_ID[fact.category].palette}, on a dark background.`,
    STYLE,
    FRAMING,
  ].join(' ')

const done = new Set(
  existsSync(CARDS_DIR) ? readdirSync(CARDS_DIR).map((file) => file.replace(/\.\w+$/, '')) : [],
)
const todo = FACTS.filter((fact) => !done.has(fact.id))

const lines = [
  '# Image prompts',
  '',
  `${todo.length} of ${FACTS.length} cards still need a picture. This file is generated by \`npm run sync\`; edit a card's \`visual\` text in \`content/\` to change its prompt.`,
  '',
  '## How to use',
  '',
  '1. Paste a prompt below into ChatGPT and generate the image.',
  '2. Save it into the `image-inbox/` folder using the card id as the file name, for example `sci-03.png`.',
  '3. Run `npm run images`. It resizes and compresses everything in the inbox into `src/assets/cards/`.',
  '4. Run `npm run sync` to refresh this list.',
  '',
  'Tip: to keep the series consistent, start a ChatGPT conversation with "I will send a series of illustration prompts. Keep the same art style across all of them." and then send prompts one at a time.',
  '',
]

for (const category of CATEGORIES) {
  const facts = todo.filter((fact) => fact.category === category.id)
  if (!facts.length) continue
  lines.push(`## ${category.name}`, '')
  for (const fact of facts) {
    lines.push(`### ${fact.id} · ${fact.title}`, '', `Save as \`${fact.id}.png\``, '', '```text', promptFor(fact), '```', '')
  }
}

mkdirSync(new URL('.', OUT), { recursive: true })
writeFileSync(OUT, lines.join('\n'))
console.log(`Wrote docs/IMAGE_PROMPTS.md with ${todo.length} prompts (${FACTS.length - todo.length} cards already have pictures).`)
